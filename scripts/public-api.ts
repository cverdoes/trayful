/**
 * Writes packages/server/public-api.md: the declaration of every name `trayful/server`
 * exports. Extensions in other repositories build on these, so a change to one shows
 * up in review as a change to this file.
 *
 * Run `pnpm api` after changing packages/server/src/public.ts or a declaration it
 * exports. `pnpm check:api` (part of `pnpm check`) fails when the committed file is out
 * of date.
 */
import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { format, resolveConfig } from 'prettier';
import ts from 'typescript';

const root = fileURLToPath(new URL('..', import.meta.url));
const server = path.join(root, 'packages/server');
const entry = path.join(server, 'src/public.ts');
const target = path.join(server, 'public-api.md');

const program = ts.createProgram([entry], {
  module: ts.ModuleKind.NodeNext,
  moduleResolution: ts.ModuleResolutionKind.NodeNext,
  target: ts.ScriptTarget.ES2022,
  strict: true,
  declaration: true,
  emitDeclarationOnly: true,
  removeComments: true,
});

/** The declarations TypeScript would publish, by the source file they come from. */
const declarations = new Map<string, ts.SourceFile>();
program.emit(undefined, (file, text) => {
  const source = file.replace(/\.d\.ts$/, '.ts');
  declarations.set(source, ts.createSourceFile(file, text, ts.ScriptTarget.ES2022));
});

const checker = program.getTypeChecker();
const entryFile = program.getSourceFile(entry);
const module = entryFile && checker.getSymbolAtLocation(entryFile);
if (!module) throw new Error(`Cannot read the exports of ${entry}.`);

const sections = checker
  .getExportsOfModule(module)
  .map((exported) => section(exported))
  .sort((a, b) => a.name.localeCompare(b.name))
  .map(({ name, from, text }) => `## ${name}\n\nFrom \`${from}\`.\n\n\`\`\`ts\n${text}\n\`\`\`\n`);

const text = await format(
  [
    '# trayful/server: public API',
    '',
    'Generated by `pnpm api` from `src/public.ts`. Do not edit by hand.',
    '',
    ...sections,
  ].join('\n'),
  { ...(await resolveConfig(target)), filepath: target },
);

if (process.argv.includes('--check')) {
  const committed = await readFile(target, 'utf8').catch(() => '');
  if (committed !== text) {
    console.error('packages/server/public-api.md is out of date. Run `pnpm api` and commit it.');
    process.exit(1);
  }
} else {
  await writeFile(target, text);
}

/** One exported name, with its published declaration and the file it comes from. */
function section(exported: ts.Symbol): { name: string; from: string; text: string } {
  const name = exported.getName();
  const symbol =
    exported.flags & ts.SymbolFlags.Alias ? checker.getAliasedSymbol(exported) : exported;
  const source = symbol.declarations?.[0]?.getSourceFile().fileName ?? '';
  const declared = declarations.get(source);
  if (!declared) throw new Error(`No declarations were emitted for ${source}.`);
  const statements = declared.statements.filter((statement) => declares(statement, name));
  if (statements.length === 0) throw new Error(`${name} is not declared in ${source}.`);
  const printed = statements.map((statement) => withoutPrivates(statement.getText(declared)));
  return { name, from: path.relative(server, source), text: printed.join('\n') };
}

function declares(statement: ts.Statement, name: string): boolean {
  if (ts.isVariableStatement(statement)) {
    return statement.declarationList.declarations.some(
      (declaration) => ts.isIdentifier(declaration.name) && declaration.name.text === name,
    );
  }
  const named = statement as ts.Statement & { name?: ts.Node };
  return named.name !== undefined && ts.isIdentifier(named.name) && named.name.text === name;
}

/** Private members are no promise to anyone, so they stay out of the snapshot. */
function withoutPrivates(declaration: string): string {
  return declaration
    .split('\n')
    .filter((line) => !/^\s+(private\b|#private)/.test(line))
    .join('\n');
}
